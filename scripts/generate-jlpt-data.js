// Deduplicate within each level (keep order) and normalize
for (const level of Object.keys(data)) {
    const seen = new Set();
    data[level] = data[level].filter(w => {
        const n = w.normalize("NFC");
        if (seen.has(n)) return false;
        seen.add(n);
        return true;
    });
}

// Remove words that appear in lower levels from higher levels
const levelOrder = ["N5", "N4", "N3", "N2", "N1"];
for (let i = 1; i < levelOrder.length; i++) {
    const current = new Set(data[levelOrder[i]].map(w => w.normalize("NFC")));
    for (let j = 0; j < i; j++) {
        const lower = new Set(data[levelOrder[j]].map(w => w.normalize("NFC")));
        for (const w of current) {
            if (lower.has(w)) {
                data[levelOrder[i]] = data[levelOrder[i]].filter(x => x.normalize("NFC") !== w);
            }
        }
    }
}

// Flatten: create a map of word -> lowest level
const wordToLevel = {};
for (const level of levelOrder) {
    for (const word of data[level]) {
        const n = word.normalize("NFC");
        if (!wordToLevel[n]) wordToLevel[n] = level;
    }
}

const output = {
    levels: data,
    count: Object.values(data).reduce((sum, arr) => sum + arr.length, 0),
    wordToLevel: wordToLevel
};

fs.writeFileSync("jlpt-data.json", JSON.stringify(output, null, 2));
